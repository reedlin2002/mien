export function translate(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = (lang === 'zh-TW' ? zh : en)[key];
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Translates text that comes from the widget registry, falling back to the English original. */
export function translateRegistry(lang: Lang, text: string | undefined): string {
  if (!text) return '';
  return lang === 'zh-TW' ? (registryZh[text] ?? text) : text;
}

export function useT() {
  const lang = usePrefs((s) => s.lang);
  const t = (key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
  t.registry = (text: string | undefined) => translateRegistry(lang, text);
  t.lang = lang;
  return t;
}
